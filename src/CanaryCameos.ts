type Beat=[Speaker,string]
const K=(text:string):Beat=>['canary',text]
const G=(text:string):Beat=>['girl',text]
const M=(text:string):Beat=>['cat',text]
const C=(text:string):Beat=>['conductor',text]
const beats=(...b:Beat[]):Conversation=>b.map(([speaker,text])=>({speaker,text}))

export const hasCanary=(lines:readonly DialogueLine[])=>lines.some(l=>l.speaker==='canary')
/** 아가씨가 이미 있거나 덧붙일 말이 없으면 원본을 그대로 돌려준다. */
export function withCameo(lines:Conversation,extra?:Conversation):Conversation{
  if(!extra||!extra.length||hasCanary(lines))return lines
  return [...lines,...extra]
}

