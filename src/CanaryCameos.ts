/**
 * 기존 이야기 속 카나리아 아가씨의 '끼어들기'.
 *
 * 아가씨는 현재 세 친구와 함께 여행한다. 그래서 이미 있던 이야기(도착 대화,
 * 풍경 행동, 마음 대화, 간식, 차장, 항해 구간·사건)에도 같은 열차의 세 번째 승객으로
 * 처음부터 함께 있었던 것처럼 한두 마디를 덧붙인다.
 *
 * 원칙
 *  - 기존 소녀·고양이·차장 대사는 가급적 보존하고, 끝에 아가씨의 말(과 가벼운 맞장구)만 덧붙인다.
 *  - 이미 아가씨가 나오는 이야기, 추억 CG가 걸린 장면(memory)에는 덧붙이지 않는다.
 *  - 보상·쿨다운·저장 데이터와 무관한 순수 텍스트 계층이다.
 */
import type {Conversation,DialogueLine,Speaker} from './Dialogue'
